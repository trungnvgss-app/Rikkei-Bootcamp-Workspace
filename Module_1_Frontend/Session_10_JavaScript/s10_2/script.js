// (Biến i kiểu số nguyên, có giá trị là 10
let i = 10;
// Biến f kiểu số thực, có giá trị là 20.5
let f = 20.5;
// Biến b kiểu logic, có giá trị là true
let b = true;
// Biến s kiểu chuỗi, có giá trị là "Hà Nội"
let s = "Hà Nội";
// Sử dụng hàm document.write() để viết kết quả ra màn hình.
document.write("i = " + i + "<br>"); // Biến i có giá trị là 10 sẽ được hiển thị
document.write("f = " + f + "<br>"); // Biến f có giá trị là 20.5 sẽ được hiển thị
document.write("b = " + b + "<br>"); // Biến b có giá trị là true sẽ được hiển thị
document.write("s = " + s + "<br>"); // Biến s có giá trị là "Hà Nội" sẽ được hiển thị
document.write("Tổng i + f = " + (i + f) + "<br>"); // Tổng của i và f sẽ được tính và hiển thị
document.write("Kết quả của b && false = " + (b && false) + "<br>"); // Kết quả của phép toán logic AND giữa b và false sẽ được tính và hiển thị
